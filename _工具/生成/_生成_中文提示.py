def main():
    if not PKG.is_dir():
        print("找不到分发包目录: %s" % PKG)
        return 1
    print("=" * 70)
    total = 0
    for name, text in MSG.items():
        # 统一成 CRLF; UTF-8 无 BOM
        body = text.replace("\r\n", "\n").replace("\n", "\r\n")
        (PKG / name).write_bytes(body.encode("utf-8"))
        size = (PKG / name).stat().st_size
        total += 1
        print("  + %-22s %6d B  (%d 行)" % (name, size, body.count("\r\n")))
    print("=" * 70)
    print("生成 %d 个中文提示文件, 全部 UTF-8 无 BOM + CRLF" % total)

    # 自检: 确认无 BOM
    bad = []
    for name in MSG:
        b = (PKG / name).read_bytes()
        if b[:3] == b"\xef\xbb\xbf":
            bad.append(name)
    print("BOM 自检:", "★ 有 BOM: %s" % bad if bad else "全部无 BOM OK")
    return 0 if not bad else 1


